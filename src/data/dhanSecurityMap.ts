export function isIndexSymbol(symbol: string): boolean {
  if (!symbol) return false;
  const clean = symbol.trim().toUpperCase().replace(/[^A-Z0-9]/g, '');
  return (
    clean === 'NIFTY' ||
    clean === 'NIFTY50' ||
    clean === 'NIFTY50INDEX' ||
    clean === 'BANKNIFTY' ||
    clean === 'NIFTYBANK' ||
    clean === 'BANKNIFTYINDEX' ||
    clean === 'FINNIFTY' ||
    clean === 'MIDCPNIFTY'
  );
}

export function getDhanSecurityId(symbol: string): string | undefined {
  if (!symbol) return undefined;
  const cleanSymbol = symbol.trim().toUpperCase().replace(/[^A-Z0-9]/g, '');

  if (cleanSymbol === 'NIFTY' || cleanSymbol === 'NIFTY50' || cleanSymbol === 'NIFTY50INDEX') {
    return '13';
  }
  if (cleanSymbol === 'BANKNIFTY' || cleanSymbol === 'NIFTYBANK' || cleanSymbol === 'BANKNIFTYINDEX') {
    return '25';
  }

  // Direct match
  if (DHAN_SECURITY_MAP[cleanSymbol]) {
    return DHAN_SECURITY_MAP[cleanSymbol];
  }

  // Try raw symbol match
  const rawSymbol = symbol.trim().toUpperCase();
  if (DHAN_SECURITY_MAP[rawSymbol]) {
    return DHAN_SECURITY_MAP[rawSymbol];
  }

  // Soft search keys
  for (const [key, secId] of Object.entries(DHAN_SECURITY_MAP)) {
    const cleanKey = key.replace(/[^A-Z0-9]/g, '');
    if (cleanKey === cleanSymbol) {
      return secId;
    }
  }

  return undefined;
}
